"""Result dataclasses for NiCo covariation analysis."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from nico_wrapper.niche.results import NicheInteractionResult


@dataclass(frozen=True)
class CovariationArtifactPaths:
    """Expected file locations for one covariation run."""

    output_dir: Path
    covariation_dir: Path
    radius: int | float
    radius_tag: str
    n_factors: int

    factors_pickle: Path
    feature_matrix_npz: Path
    regression_dir: Path

    state_pickle: Path
    manifest_json: Path
    regression_tsv: Path


@dataclass(frozen=True)
class CovariationResult:
    """Stable result object returned by the covariation wrapper."""

    output_dir: Path
    covariation_dir: Path

    radius: int | float
    radius_tag: str
    n_factors: int
    modality: str

    factors_pickle: Path
    feature_matrix_npz: Path
    regression_dir: Path

    state_pickle: Path | None = None
    manifest_json: Path | None = None
    regression_tsv: Path | None = None

    niche_result: NicheInteractionResult | None = None
    cell_type_names: dict[int, str] | None = None

    nico_result: Any | None = None


@dataclass(frozen=True)
class CovariationReportOutputs:
    """Paths generated by optional covariation report generation."""

    regression_circleplots: tuple[Path, ...] = ()
    regression_heatmaps: tuple[Path, ...] = ()
    gene_correlation_excel: Path | None = None
    factor_gene_heatmaps: tuple[Path, ...] = ()
    ligand_receptor_summary_xlsx: Path | None = None
    regression_summary_txt: Path | None = None
    ligand_receptor_plots: tuple[Path, ...] = ()
    pathway_figures: tuple[Path, ...] = ()
    top_gene_outputs: tuple[Path, ...] = ()
    top_gene_plots: tuple[Path, ...] = ()
    umap_plots: tuple[Path, ...] = ()
    feature_matrix_plot: Path | None = None
    report_manifest_json: Path | None = None
    other_outputs: tuple[Path, ...] = ()
